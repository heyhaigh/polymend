// Make changelog.html, the "Changelog" page, from CHANGELOG.md, so the page and the file in
// the repository always say the same thing. A test fails if the page is out of date.
// Usage: node tools/make-changelog.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const escape = text => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const inline = text => escape(text).replace(/`([^`]+)`/g, '<code>$1</code>');

export function changelogPage(markdown) {
  const lines = markdown.replace(/\r/g, '').split('\n');
  const body = [];
  let title = 'Changelog', lede = '', list = false;
  const closeList = () => { if (list) { body.push('      </ul>'); list = false; } };
  for (const raw of lines) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith('# ')) { title = line.slice(2); continue; }
    if (line.startsWith('## ')) {
      closeList();
      const [, version, when] = /^## (\S+)(?: \((.+)\))?$/.exec(line) || [null, line.slice(3), ''];
      body.push(`\n      <h2 id="v${escape(version)}">Version ${escape(version)}${when ? ` <span class="when">${escape(when)}</span>` : ''}</h2>`);
      continue;
    }
    const heading = /^\*\*(.+)\*\*$/.exec(line);
    if (heading) { closeList(); body.push(`      <h3>${inline(heading[1])}</h3>`); continue; }
    if (line.startsWith('- ')) {
      if (!list) { body.push('      <ul>'); list = true; }
      body.push(`        <li>${inline(line.slice(2))}</li>`);
      continue;
    }
    closeList();
    if (!lede && !body.length) { lede = line; continue; }
    body.push(`      <p>${inline(line)}</p>`);
  }
  closeList();
  return `<!doctype html>
<!-- Made from CHANGELOG.md by tools/make-changelog.mjs. Do not edit this file. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escape(title)} · Polymend</title>
  <meta name="description" content="What has changed in Polymend, the free browser-based STL and GLB mesh repair tool, version by version.">
  <link rel="canonical" href="https://polymend.xyz/changelog">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="Polymend">
  <meta property="og:title" content="Changelog · Polymend">
  <meta property="og:description" content="What has changed in Polymend, the free browser-based STL and GLB mesh repair tool, version by version.">
  <meta property="og:url" content="https://polymend.xyz/changelog">
  <meta property="og:image" content="https://polymend.xyz/og-image.jpg">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="Polymend. A 3D figure shown before and after repair, with the repaired spots marked.">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:image" content="https://polymend.xyz/og-image.jpg">
  <link rel="icon" href="/favicon.svg" type="image/svg+xml">
  <link rel="icon" href="/favicon-48.png" type="image/png" sizes="48x48">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'self'; style-src 'self'; font-src 'self'; img-src 'self' data:; connect-src 'none'; base-uri 'none'; form-action 'none'">
  <link rel="preload" href="/app/fonts/GeistMono-Variable.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="stylesheet" href="/app/style.css">
  <script src="/app/theme.js"></script>
</head>
<body>
  <div class="controls-group">
    <button id="theme-toggle" class="theme-toggle" type="button" aria-label="Toggle dark mode" title="Toggle theme (T)"></button>
  </div>
  <main class="tool-container">
    <article class="prose">
      <p class="prose-back"><a href="/">Polymend</a></p>
      <h1 class="tool-title">${escape(title)}</h1>
      <p class="prose-lede">${inline(lede)}</p>
${body.join('\n')}
    </article>
    <nav class="site-links" aria-label="About this site">
      <a href="/privacy">Privacy</a>
      <a href="/terms">Terms</a>
      <a href="/changelog">Changelog</a>
      <a href="mailto:feedback@polymend.xyz?subject=Polymend%20feedback">Send feedback</a>
      <a href="https://github.com/heyhaigh/polymend">GitHub</a>
      <a href="/#embed">Embed on your site</a>
    </nav>
    <p class="credit">
      <a href="https://heyhaigh.ai/">
        <img src="/app/ry-hand-96.webp" alt="" width="32" height="32">
        <span>Created by Ryan Haigh</span>
      </a>
    </p>
  </main>
</body>
</html>
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, 'changelog.html'), changelogPage(fs.readFileSync(path.join(root, 'CHANGELOG.md'), 'utf8')));
  console.log('changelog.html written');
}
